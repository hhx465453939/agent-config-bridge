const HERE = dirname(fileURLToPath(import.meta.url));

/**
 * The filesystem probe the policy consults.
 *
 * Everything here answers instead of throwing: a probe that throws turns a
 * filesystem hiccup into a dead gate, and a gate that stops existing is the one
 * failure this design is built to avoid. `listDir` and `statMtime` exist for
 * the index-freshness rule; the plain `exists` is what scoping uses.
 */
export const realFs = {
  exists: (p) => existsSync(p),
  isFile: (p) => {
    try {
      return statSync(p).isFile();
    } catch {
      return false;
    }
  },
  isDirectory: (p) => {
    try {
      return statSync(p).isDirectory();
    } catch {
      return false;
    }
  },
  statMtime: (p) => {
    try {
      return statSync(p).mtimeMs;
    } catch {
      return 0;
    }
  },
  listDir: (dir) => {
    try {
      return readdirSync(dir);
    } catch {
      return [];
    }
  },
  /**
   * Source text of a file, for the AI4S "does the script log?" check.
   * `null` (not a throw) when it cannot be read: an unreadable script is not
   * evidence that its author forgot logging, so the check must abstain.
   */
  readText: (p) => {
    try {
      return readFileSync(p, 'utf8');
    } catch {
      return null;
    }
  },
};

/**
 * Where the policy JSON can live.
 *
 * Two layouts have to work, and getting this wrong fails SILENTLY (the gate
 * falls back to fail-open), which is the worst possible failure mode for an
 * enforcement point:
 *
 *   repo checkout : bridge/gates/pi/policy.json      <- next to this adapter
 *   installed     : <gate dir>/pi/index.js
 *                   <gate dir>/policy.json          <- generated by the installer
 *
 * So the adapter-local file is checked first (developer layout), then the gate
 * root (installed layout). A caller-supplied path always wins.
 */
export const policyCandidates = (here, explicit) =>
  [explicit, join(here, 'policy.json'), join(here, '..', 'policy.json')].filter(Boolean);

export const firstExistingPolicy = (here, explicit, exists = existsSync) => {
  for (const candidate of policyCandidates(here, explicit)) {
    if (exists(candidate)) return candidate;
  }
  return null;
};

/** Tool names that count as "the model consulted the code graph". */
const SIGNAL_TOOLS = [
  'search_graph',
  'trace_path',
  'get_code_snippet',
  'query_graph',
  'get_architecture',
  'search_code',
];

/**
 * Tool-name aliases. pi's own tools are read/write/edit/bash, but extensions
 * and other harnesses reuse the same policy with `read_file`, `apply_patch`,
 * `str_replace_editor` and friends. An unknown write tool used to fall through
 * the adapter untouched — a silent bypass for Layer 0 and the secret rule.
 */
const READ_TOOLS = new Set(['read', 'read_file', 'view', 'open_file']);
const WRITE_TOOLS = new Set([
  'write', 'edit', 'apply_patch', 'str_replace_editor', 'create_file', 'multi_edit', 'notebook_edit',
  'write_file', 'append_file', 'delete_file',
]);

/** The path spelling a tool input uses, whichever harness it came from. */
const inputPath = (input) => input?.path ?? input?.file_path ?? null;

/** The text a write tool is about to insert, across the common schemas. */
const inputContent = (input) =>
  [input?.content, input?.newText, input?.new_string, input?.patch, input?.text]
    .find((v) => typeof v === 'string') ?? null;

const isSignalTool = (name) =>
  SIGNAL_TOOLS.some((s) => name === s || name.endsWith(`_${s}`));

/**
 * Fallback when policy.json cannot be read.
 *
 * v4 fails CLOSED for the safety rules instead of returning `checks: []`.
 * A malformed policy used to make the gate disappear silently — the one failure
 * mode this whole design exists to prevent. Research rules stay off (they need
 * reliable session state), but secrets, out-of-scope writes and destructive
 * commands keep being enforced, and the session is told it is degraded.
 */
const fallback = (why) => ({
  policy: {
    name: 'enforce-rules',
    version: 1,
    description: 'degraded safety-only policy because the policy file could not be read',
    reminded:
      `[system-reminder · 门控降级] policy.json 读取失败，完整规则已停用；` +
      `安全底线仍在（凭据写入 / 越界写入 / 破坏性命令）。请修复：${why}`,
    checks: ['no-write-outside', 'no-secret-write', 'no-destructive-bash'],
    config: { max_blocks_per_session: 0, signal_ttl_ms: 0 },
  },
  error: why,
});

/** Append text to a pi message content, which is either a string or blocks. */
const appendText = (content, text) => {
  if (typeof content === 'string') return `${content}\n\n${text}`;
  if (Array.isArray(content)) return [...content, { type: 'text', text }];
  return content; // unknown shape: leave it alone rather than corrupt it
};

export default function enforceRules(pi, options = {}) {
  const resolved = firstExistingPolicy(HERE, options.policyPath ?? null);
  const loaded = options.policy
    ? policyFromObject(options.policy)
    : resolved
      ? loadPolicy(resolved)
      : {
          ok: false,
          error:
            `no policy file found; looked in:\n` +
            policyCandidates(HERE, options.policyPath ?? null)
              .map((c) => `    ${c}`)
              .join('\n'),
        };
  const { policy: loadedPolicy, error } = loaded.ok
    ? loaded
    : fallback(`policy not loaded (${loaded.error})`);
  /**
   * A grant made through `/gate` lives in the machine-local override. Applying
   * it here means the grant takes effect immediately instead of at the next
   * `bridge apply` - and it keeps the installed `policy.json` and the live
   * override from ever disagreeing about a tier.
   */
  const policy = applyMachineOverride(loadedPolicy);

  const state = newSessionState();
  /** Set once per session so the same advisory is not repeated. */
  let noticedPolicyProblem = false;
  /**
   * Cache of the last classification, keyed by (cwd, prompt).
   *
   * `before_agent_start` can fire again for the same user request (retry,
   * recovery, compaction). Re-classifying would spend another model round trip
   * and - worse - could land on a different answer, silently switching the rule
   * set mid-turn for reasons the user cannot see.
   */
  let lastClassified = { key: null, result: null };
  /**
   * The directory pi resolves a relative tool path against.
   *
   * pi's `read` schema accepts "relative or absolute" and resolves the relative
   * form against the session directory, so a rule that only understands
   * absolute paths would be dodged by spelling the same file relatively. The
   * value is captured at session start and refreshed from `ctx` on every call,
   * because `ctx.cwd` is not guaranteed on every event.
   *
   * Left null when nothing has ever supplied one: guessing here would scope a
   * read into whatever directory the pi process happened to start in, which is
   * a different repository. Without a cwd the path stays relative, the policy
   * refuses it, and the gate is inert — the same behaviour as before this was
   * fixed, and the honest floor.
   */
  let sessionCwd = null;
  const cwdFor = (ctx) =>
    typeof ctx?.cwd === 'string' && ctx.cwd ? ctx.cwd : sessionCwd;

  pi.on('session_start', async (_event, ctx) => {
    state.blocks = 0;
    state.firstBlockAt = 0;
    state.signals = 0;
    state.lastIndexRefreshAt = 0;
    state.slackContinues = 0;
    state.written.clear();
    state.unlocks.clear();
    state.inspected.clear();
    state.docReads.clear();
    state.failedCommands.clear();
    state.destructiveGrants.clear();
    state.lastInvestigationAt = 0;
    state.profile = policy.defaultProfile ?? 'general-dev';
    state.profileSource = 'fallback';
    state.scriptsRun.clear();
    state.turnStart = 0;
    lastClassified = { key: null, result: null };
    if (typeof ctx?.cwd === 'string' && ctx.cwd) sessionCwd = ctx.cwd;
    if (error) {
      // A gate that cannot load its policy is OFF. Say so loudly: in a headless
      // run there is no UI to notify, so this also goes to stderr. A silent
      // no-op enforcement point is worse than no enforcement point at all,
      // because everyone believes the rules are being enforced.
      process.stderr.write(`[enforce-rules] DISABLED: ${error}\n`);
      if (ctx?.hasUI && !noticedPolicyProblem) {
        noticedPolicyProblem = true;
        ctx.ui.notify(`enforce-rules: ${error}; gate is inactive`, 'warn');
      }
      return;
    }
    if (ctx?.hasUI) {
      ctx.ui.notify(
        `enforce-rules: ${policy.name} active (${policy.checks.join(', ') || 'no checks'})`,
        'info',
      );
    }
  });

  /**
   * v5: classify the session's domain once per user turn.
   *
   * Deliberately HERE and not in `tool_call`. `tool_call` runs for every single
   * tool invocation, so a model-backed judge there would add a network round trip
   * to every read — the kind of latency that gets a gate uninstalled. This event
   * fires once per user request, which is the right granularity for "what kind of
   * work is this?"
   *
   * Runs started by `pi.sendMessage(..., { triggerTurn: true })` carry no prompt
   * (`messageType === 'custom'`). They continue work the user already asked for,
   * so the previous classification is kept instead of being re-derived from an
   * empty prompt — which would always answer `general-dev`.
   */
  pi.on('before_agent_start', async (event, ctx) => {
    const cwd = cwdFor(ctx) ?? '';
    // A new user turn is the boundary the output checks (W2) compare mtimes to.
    state.turnStart = Date.now();
    if (event?.messageType === 'custom') return;
    const prompt = typeof event?.prompt === 'string' ? event.prompt : '';
    const key = `${cwd}\u0000${prompt}`;
    if (lastClassified.key === key && lastClassified.result) {
      state.profile = lastClassified.result.profile;
      state.profileSource = lastClassified.result.source;
      return;
    }
    const result = await classify({
      cwd,
      prompt,
      fs: realFs,
      policy,
      // No judge is wired by default (`classifier.model_judge` is false), so T2
      // is normally skipped. A host may inject one; tests always do not.
      modelHint: typeof options.modelHint === 'function' ? options.modelHint : null,
    });
    lastClassified = { key, result };
    state.profile = result.profile;
    state.profileSource = result.source;
    if (result.source !== 'fingerprint' && ctx?.hasUI) {
      // A fingerprint hit is a fact, not news; the weaker verdicts are worth one
      // line so a mis-classification is visible instead of silent.
      ctx.ui.notify(`enforce-rules: domain ${result.profile} (${result.source})`, 'info');
    }
  });

  pi.on('tool_call', async (event, ctx) => {
    // MCP gateway: the real tool and its arguments live under input.tool/args.
    // Before v4 the adapter returned early for every `mcp` call, so a proxied
    // write/read/bash was silently exempt from every rule below.
    const proxied =
      event.toolName === 'mcp' && typeof event.input?.tool === 'string' ? event.input.tool : '';
    const name = proxied || event.toolName;
    const input = proxied ? (event.input?.args ?? {}) : event.input;
    const shell = name === 'powershell' ? 'powershell' : 'bash';
    const cwd = cwdFor(ctx);
    // The profile decides the check LIST, never the signature: `shouldBlock`
    // still receives `{policy, input, state, fs}`, so the rule layer never learns
    // that domains exist (ADR-003 §strategy/adapter split).
    const effective = profilePolicy(policy, state.profile);

    // Remember what this session wrote: reading your own output is never a
    // violation, and blocking it would make the gate fight normal development.
    // The record happens only AFTER the checks pass. Recording first (as v2
    // did) would put the target in `written` and exempt the very write that
    // Layer 0 was supposed to question.
    const writeLike =
      WRITE_TOOLS.has(name) ||
      (!READ_TOOLS.has(name) && typeof inputPath(input) === 'string' && typeof inputContent(input) === 'string');
    if (writeLike) {
      const path = normalizePath(inputPath(input), cwd);
      const content = inputContent(input);
      const verdict = shouldBlock({
        policy: effective,
        input: { action: 'write', path, tool: name, content },
        state,
        fs: realFs,
      });
      if (verdict.block) {
        if (ctx?.hasUI) {
          ctx.ui.notify(
            `enforce-rules [${verdict.code}] block ${state.blocks}/${policy.config.max_blocks_per_session}`,
            'warn',
          );
        }
        return { block: true, reason: verdict.reason };
      }
      recordWrite(state, path);
      recordInvestigation(state);
      return;
    }

    // Bash/PowerShell reads count as reads. `cat src/a.ts`, `grep x packages/…`,
    // `sed -n '1,20p' file` and `Get-Content src/a.ts` are the same act as the
    // `read` tool; leaving them ungated was the hole that made the gate
    // cosmetic (2026-10-16). PowerShell was added in v4 because enabling that
    // tool used to be a full bypass on Windows.
    if (name === 'bash' || name === 'powershell') {
      const command = typeof input?.command === 'string' ? input.command : '';
      const verdict = shouldBlock({
        policy: effective,
        input: {
          action: 'bash',
          path: null,
          tool: name,
          shell,
          command,
          cwd,
        },
        state,
        fs: realFs,
      });
      if (verdict.block) {
        if (ctx?.hasUI) {
          ctx.ui.notify(
            `enforce-rules [${verdict.code}] block ${state.blocks}/${policy.config.max_blocks_per_session}`,
            'warn',
          );
        }
        return { block: true, reason: verdict.reason };
      }
      // Three-tier permission model (CHG-20261105 v2): a `confirm` finding is
      // not a refusal. pi itself does NOT ask before running a tool
      // (`docs/security.md`: "it does not ask for approval before every tool
      // call"), so the question has to come from here.
      //
      // Three options, not two: "allow once" and "allow this whole class for
      // this session" are different promises, and collapsing them either
      // nags on every file or silently grants more than the user meant.
      if (verdict.confirm) {
        const why = verdict.confirmReason ?? '破坏性命令需要确认';
        const category = verdict.confirmCategory ?? 'delete';
        if (ctx?.hasUI && typeof ctx.ui?.select === 'function') {
          const options = [
            '允许这一次',
            `本会话允许「${category}」这一类`,
            '拒绝',
          ];
          const choice = await ctx.ui.select(why, options);
          if (choice === options[1]) {
            state.destructiveGrants.set(category, 'allow');
            ctx.ui.notify?.(
              `enforce-rules: 本会话已允许「${category}」。收回：/gate deny ${category}`,
              'info',
            );
          } else if (choice !== options[0]) {
            return { block: true, reason: `${why}\n\n用户拒绝了这次执行。` };
          }
        } else if (ctx?.hasUI && typeof ctx.ui?.confirm === 'function') {
          // Older harness builds only expose a yes/no dialog.
          const allowed = await ctx.ui.confirm('允许执行这条破坏性命令？', command);
          if (!allowed) {
            return { block: true, reason: `${why}\n\n用户拒绝了这次执行。` };
          }
        } else {
          // No UI: an automated run already carries the user's authorization in
          // its own invocation, and blocking there would make the gate
          // unusable from scripts. Record the decision on stderr instead of
          // waiting for a dialog that can never appear. The guardrail tier
          // above still refuses, so nothing unrecoverable slips through here.
          process.stderr.write(
            `[enforce-rules] DESTRUCTIVE_CONFIRM auto-approved (no UI) [${category}]: ${command.slice(0, 200)}\n`,
          );
        }
      }
      // AI4S: remember the script this call is about to run. W1 uses the key set
      // to ask for a Worklog only on the FIRST run of a given script, and the
      // turn-end W4 check uses `startedAt` to date the log it expects.
      for (const script of analysisScriptTargets(command, {
        config: effective.config,
        cwd,
        isFile: realFs.isFile,
      })) {
        recordScriptRun(state, script);
      }
      return;
    }

    if (!READ_TOOLS.has(name)) return;

    const verdict = shouldBlock({
      policy: effective,
      input: { action: 'read', path: normalizePath(inputPath(input), cwd), tool: name },
      state,
      fs: realFs,
    });

    if (verdict.block) {
      if (ctx?.hasUI) {
        ctx.ui.notify(
          `enforce-rules [${verdict.code}] block ${state.blocks}/${policy.config.max_blocks_per_session}`,
          'warn',
        );
      }
      return { block: true, reason: verdict.reason };
    }

    if (verdict.capReached && ctx?.hasUI && !noticedPolicyProblem) {
      noticedPolicyProblem = true;
      ctx.ui.notify(
        'enforce-rules: block cap reached for this window; research rules resume after the reset window',
        'warn',
      );
    }
    return;
  });

  /** All string leaves of a tool input, so a query's arguments become unlocks. */
  const inputStrings = (value, out = []) => {
    if (typeof value === 'string') out.push(value);
    else if (Array.isArray(value)) for (const item of value) inputStrings(item, out);
    else if (value && typeof value === 'object') for (const item of Object.values(value)) inputStrings(item, out);
    return out;
  };

  /** Text of a tool result, for the shape pi reports (`{content:[{text}]}`). */
  const resultText = (result) => {
    if (typeof result === 'string') return result;
    if (!result || typeof result !== 'object') return '';
    if (typeof result.text === 'string') return result.text;
    if (Array.isArray(result.content)) {
      return result.content
        .map((block) => (typeof block === 'string' ? block : typeof block?.text === 'string' ? block.text : ''))
        .join('\n');
    }
    return '';
  };

  pi.on('tool_result', async (event, ctx) => {
    const cwd = cwdFor(ctx);
    // Unwrap the MCP gateway once; every branch below works on the real tool.
    const proxied =
      event.toolName === 'mcp' && typeof event.input?.tool === 'string' ? event.input.tool : '';
    const toolName = proxied || event.toolName;
    const input = proxied ? (event.input?.args ?? {}) : event.input;
    const command = typeof input?.command === 'string' ? input.command : '';
    const shell = toolName === 'powershell' ? 'powershell' : 'bash';

    if (event.isError) {
      // A failed shell command feeds the blind-retry rule. A failed graph query
      // must not record a signal — the model has learned nothing yet.
      if (toolName === 'bash' || toolName === 'powershell') {
        recordCommandResult(state, command, true);
      }
      return;
    }

    // A successful read is evidence about the exact file, which is what Layer 0
    // needs before an edit. Convention documents additionally satisfy the
    // "project conventions" question.
    const path = normalizePath(inputPath(input), cwd);
    if (READ_TOOLS.has(toolName) && path) {
      recordInspection(state, path);
      if (isConventionDoc(path, policy.config) || isChgContract(path, policy.config)) {
        recordDocRead(state, path);
      }
    }

    if (toolName === 'bash' || toolName === 'powershell') {
      recordCommandResult(state, command, false);
      for (const target of shellReadTargets({ command, shell }, {
        config: policy.config,
        cwd,
        isFile: realFs.isFile,
        exists: realFs.exists,
      })) {
        recordInspection(state, normalizePath(target));
      }
      // `cat CONTRIBUTING.md` satisfies the convention rule just like `read`.
      for (const token of command.match(/"[^"]+"|'[^']+'|[^\s;&|]+/g) ?? []) {
        const candidate = normalizePath(token.replace(/^["']|["']$/g, ''), cwd);
        if (
          candidate &&
          (isConventionDoc(candidate, policy.config) || isChgContract(candidate, policy.config)) &&
          realFs.isFile(candidate)
        ) {
          recordDocRead(state, candidate);
        }
      }
    }

    // A successful index refresh is Layer-2 evidence that works even when the
    // index lives in a global data directory (no repo-local marker). Re-indexing
    // also changes a marker's mtime, so a cached value must be dropped.
    if (
      toolName === 'index_repository' ||
      toolName.endsWith('_index_repository') ||
      toolName === 'detect_changes' ||
      toolName.endsWith('_detect_changes')
    ) {
      resetMtimeCache();
      recordIndexRefresh(state);
    }

    if (!isSignalTool(toolName)) return;

    // A successful call is not enough: an empty result ("total":0) used to buy
    // a full read window without telling the model anything. Only evidence
    // counts; the policy can turn this off when a harness cannot see results.
    // pi reports a tool result as `event.content` (plus optional
    // `structuredContent`), not `event.result`. Prefer the legacy field when a
    // harness supplies it, then the real pi event shape.
    const resultBody = resultText(event.result ?? event);
    if (!graphResultIsEvidence(resultBody, policy.config)) return;

    const now = Date.now();
    recordSignal(state, now);
    // …and remember *what the query was about*: arguments plus the result text
    // become scoped unlocks, so a query about one file/package never buys a
    // free pass for the whole repository — but the file it named stays readable
    // for `unlock_ttl_ms` without another round-trip.
    recordUnlocks(state, unlockTokensFromText(inputStrings(input).join('\n')), now);
    if (typeof input?.qualified_name === 'string') {
      recordUnlocks(state, unlockTokensFromQualifiedName(input.qualified_name), now);
    }
    recordUnlocks(state, unlockTokensFromText(resultBody), now);
  });

  /**
   * Turn-level anti-slack (v4).
   *
   * A tool-call gate cannot see a reply that does no work at all. `turn_end` is
   * the boundary where the assistant's final text is available; returning
   * `continue: true` asks for one more turn instead of handing a promise to the
   * user as if it were a delivery. Bounded by `slack_max_continues` so a false
   * positive cannot loop the agent forever.
   */
  pi.on('turn_end', async (event, ctx) => {
    if (event.message?.role !== 'assistant') return;
    const max = policy.config.slack_max_continues ?? 0;
    if (max <= 0 || state.slackContinues >= max) return;

    // AI4S output artifacts (W4 log file / W2 result README). Deliberately a
    // `continue` and not a `deny`: both are discovered after the computation has
    // finished, and one more turn is enough to fix them. Blocking a call that
    // already completed would only break a finished analysis.
    //
    // `outputArtifactFindings` returns [] for a general-dev session (no result
    // dirs, no scripts), so the cost on ordinary work is one Map lookup.
    const effective = profilePolicy(policy, state.profile);
    const artifacts = outputArtifactFindings({
      policy: effective,
      state,
      fs: realFs,
      cwd: cwdFor(ctx),
    });
    if (artifacts.length > 0) {
      state.slackContinues += 1;
      if (ctx?.hasUI) {
        ctx.ui.notify(
          `enforce-rules [${artifacts[0].code}] continue ${state.slackContinues}/${max}`,
          'warn',
        );
      }
      return {
        continue: true,
        entries: [
          ...(event.entries ?? []),
          {
            type: 'custom_message',
            customType: 'enforce-rules-ai4s-output',
            content: artifacts.map((f) => f.reason).join('\n\n'),
            display: false,
          },
        ],
      };
    }

    if (policy.config.slack_check === false) return;

    const finding = slackFinding(resultText(event.message), policy.config);
    if (!finding) return;

    state.slackContinues += 1;
    if (ctx?.hasUI) {
      ctx.ui.notify(
        `enforce-rules [${finding.code}] continue ${state.slackContinues}/${max}`,
        'warn',
      );
    }
    return {
      continue: true,
      entries: [
        ...(event.entries ?? []),
        {
          type: 'custom_message',
          customType: 'enforce-rules-no-slack',
          content: finding.reason,
          display: false,
        },
      ],
    };
  });

  /**
   * `/gate` - the only supported way to change a permission tier.
   *
   * Deliberately a user-typed command and not a tool. A grant must be given by
   * the user, never taken by the agent: the `no-self-grant` check refuses any
   * write or shell redirect that carries `destructive_grants`, which closes the
   * obvious "agent edits its own permission file" hole.
   *
   * Persistent grants go to the machine-local override, never to the installed
   * `policy.json`: `bridge apply` regenerates that file, so a grant written
   * there would be silently lost at the next apply.
   */
  // A harness build without `registerCommand` (or a test double) loses `/gate`,
  // not enforcement. A missing capability must degrade one feature, never take
  // the security layer down with it - the same rule the UI probes follow.
  const registerGateCommand =
    typeof pi.registerCommand === 'function' ? pi.registerCommand.bind(pi) : null;
  registerGateCommand?.('gate', {
    description:
      '破坏性操作授权：list / grant <类别> / ask <类别> / deny <类别> / reset <类别> / session <类别>',
    handler: async (args, ctx) => {
      const notify = (text, level = 'info') => ctx?.ui?.notify?.(text, level);
      const tokens = String(args ?? '').trim().split(/\s+/).filter(Boolean);
      const sub = (tokens[0] ?? 'list').toLowerCase();
      const category = tokens[1] ?? null;
      const categories = Object.keys(DESTRUCTIVE_CATEGORIES);

      const report = () => {
        const merged = applyMachineOverride(policy);
        const rows = categories.map((name) => {
          const tier = effectiveDestructiveTier(name, merged.config, state);
          const grant = merged.config.destructive_grants?.[name] ?? 'confirm';
          const session = state.destructiveGrants.get(name);
          return (
            `  ${name.padEnd(18)} ${tier.padEnd(8)}（policy: ${grant}${session ? `，本会话: ${session}` : ''}）\n` +
            `      ${DESTRUCTIVE_CATEGORIES[name]}`
          );
        });
        return [
          '破坏性操作授权档位（allow=直接执行 / confirm=询问 / deny=拒绝）',
          '',
          ...rows,
          '',
          '红线（任何授权都不放行）：删 $HOME、删 cwd、含 .. 的路径、磁盘格式化、裸设备写入、关机重启。',
          '',
          '调整：/gate grant <类别>    持久允许',
          '      /gate ask <类别>      改为每次询问',
          '      /gate deny <类别>     拒绝',
          '      /gate reset <类别>    恢复默认',
          '      /gate session <类别>  仅本会话允许',
        ].join('\n');
      };

      if (sub === 'list' || sub === 'status') {
        notify(report());
        return;
      }

      if (!category || !categories.includes(category)) {
        notify(`未知类别：${category ?? '(空)'}\n可用：${categories.join(', ')}`, 'warn');
        return;
      }

      if (sub === 'session') {
        state.destructiveGrants.set(category, 'allow');
        notify(`本会话已允许「${category}」（仅本会话，重开会话失效）。收回：/gate deny ${category}`);
        return;
      }

      if (!['grant', 'ask', 'deny', 'reset'].includes(sub)) {
        notify(`未知子命令：${sub}\n\n${report()}`, 'warn');
        return;
      }

      const file = machineGateConfigPath();
      if (!file) {
        notify('无法定位机器本地配置目录（HOME / USERPROFILE 均未设置）。', 'error');
        return;
      }

      let doc = {};
      if (existsSync(file)) {
        try {
          doc = JSON.parse(readFileSync(file, 'utf8')) ?? {};
        } catch (err) {
          notify(`${file} 不是合法 JSON，先修好它：${err.message}`, 'error');
          return;
        }
      }
      if (!doc || typeof doc !== 'object' || Array.isArray(doc)) doc = {};
      if (!doc.config || typeof doc.config !== 'object' || Array.isArray(doc.config)) doc.config = {};
      if (
        !doc.config.destructive_grants ||
        typeof doc.config.destructive_grants !== 'object' ||
        Array.isArray(doc.config.destructive_grants)
      ) {
        doc.config.destructive_grants = {};
      }

      if (sub === 'reset') {
        delete doc.config.destructive_grants[category];
      } else {
        doc.config.destructive_grants[category] =
          sub === 'grant' ? 'allow' : sub === 'ask' ? 'confirm' : 'deny';
      }

      try {
        mkdirSync(dirname(file), { recursive: true });
        writeFileSync(file, `${JSON.stringify(doc, null, 2)}\n`, 'utf8');
      } catch (err) {
        notify(`写入 ${file} 失败：${err.message}`, 'error');
        return;
      }

      const merged = applyMachineOverride(policy);
      notify(
        sub === 'reset'
          ? `「${category}」已恢复默认档位。\n\n${report()}`
          : `「${category}」已设为 ${merged.config.destructive_grants?.[category] ?? 'confirm'}（持久，写在 ${file}）。\n\n${report()}`,
      );
    },
  });

  pi.on('context', async (event) => {
    const reminder = reminderFor(policy, state);
    if (!reminder) return;
    const messages = event.messages;
    if (!Array.isArray(messages) || messages.length === 0) return;

    const last = messages[messages.length - 1];
    if (last?.role === 'user') {
      messages[messages.length - 1] = {
        ...last,
        content: appendText(last.content, reminder),
      };
    } else {
      messages.push({ role: 'user', content: reminder });
    }
    return { messages };
  });
}
